/**
 * Regenerate the TOURS list inside docs/apps-script-feedback-form.gs.
 *
 * The feedback form has all 48 tours baked in, because Apps Script cannot read
 * lib/tours.ts. That means ADDING A TOUR TO THE SITE DOES NOT ADD IT TO THE
 * FORM — the new tour simply has no link and appears in no picker, and nobody
 * notices until a client cannot find their trip.
 *
 * Run this after adding, renaming or removing a tour:
 *
 *     node scripts/build-feedback-form.mjs
 *
 * Then re-run createForm() in the Apps Script editor. __tests__/lib/
 * feedback-form-tours.test.ts fails if you forget.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const GS = path.join(ROOT, "docs", "apps-script-feedback-form.gs");

/**
 * A .js twin of the same script.
 *
 * .gs is what Apps Script calls its files, but editors have no handler for it,
 * so clicking the path in a terminal or an editor link does nothing. The twin
 * exists purely to be openable. .gs stays the source of truth; this file is
 * written from it on every run, and __tests__/lib/feedback-form-tours.test.ts
 * fails if the two ever drift, so you can never paste a stale copy.
 */
const JS_TWIN = path.join(ROOT, "docs", "apps-script-feedback-form.js");

/** Parse the catalogue without importing TypeScript. */
export function readTours() {
  const src = fs.readFileSync(path.join(ROOT, "lib", "tours.ts"), "utf8");
  const records = src.split(/\n  \{\n/).slice(1);
  const tours = [];
  for (const r of records) {
    const grab = (re) => (r.match(re) || [, ""])[1];
    const slug = grab(/slug: "([^"]+)"/);
    if (!slug) continue;
    const duration = grab(/duration: "([^"]+)"/);
    const dm = duration.match(/(\d+)\s*day/i);
    let cat = grab(/category: "([^"]+)"/);
    if (cat === "hiking") cat = "trekking"; // one bucket for the client
    tours.push({
      slug,
      title: grab(/title: "([^"]+)"/),
      cat,
      origin: grab(/origin: "([^"]+)"/),
      days: dm ? Number(dm[1]) : 1,
      type: grab(/tourType: "([^"]+)"/) || "private",
    });
  }
  return tours;
}

/** Sorted the way a human scans it: city, then kind, then length. */
export function sortTours(tours) {
  const origin = { marrakech: 0, agadir: 1, casablanca: 2 };
  const cat = { desert: 0, trekking: 1, cultural: 2, "day-tours": 3 };
  return [...tours].sort(
    (a, b) =>
      (origin[a.origin] ?? 99) - (origin[b.origin] ?? 99) ||
      (cat[a.cat] ?? 99) - (cat[b.cat] ?? 99) ||
      a.days - b.days ||
      a.title.localeCompare(b.title),
  );
}

export function renderLiteral(tours) {
  const lines = sortTours(tours).map(
    (t) =>
      `  { slug: ${JSON.stringify(t.slug)}, title: ${JSON.stringify(t.title)}, ` +
      `cat: ${JSON.stringify(t.cat)}, origin: ${JSON.stringify(t.origin)}, ` +
      `days: ${t.days}, type: ${JSON.stringify(t.type)} },`,
  );
  return (
    "/** Generated by scripts/build-feedback-form.mjs. Do not hand-edit. */\nvar TOURS = [\n" +
    lines.join("\n") +
    "\n];\n"
  );
}

if (process.argv[1] && process.argv[1].endsWith("build-feedback-form.mjs")) {
  const tours = readTours();
  const missing = tours.filter((t) => !t.title || !t.cat || !t.origin);
  if (missing.length) {
    console.error("Tours missing required fields:", missing.map((m) => m.slug));
    process.exit(1);
  }

  const gs = fs.readFileSync(GS, "utf8");
  const start = gs.indexOf("var TOURS = [");
  const end = gs.indexOf("];", start);
  if (start < 0 || end < 0) {
    console.error("Could not find the TOURS block in " + GS);
    process.exit(1);
  }
  // Swallow whatever comment line sits directly above the array, so re-running
  // replaces it instead of stacking a second one on top. Checked by cmp in the
  // build: the generator must be idempotent, or the file grows every run.
  let from = start;
  const before = gs.slice(0, start);
  const lastLineBreak = before.lastIndexOf("\n", before.length - 2);
  const priorLine = before.slice(lastLineBreak + 1).trim();
  if (priorLine.startsWith("/**") && priorLine.endsWith("*/")) from = lastLineBreak + 1;

  const next = gs.slice(0, from) + renderLiteral(tours) + gs.slice(end + 3);
  fs.writeFileSync(GS, next);
  fs.writeFileSync(JS_TWIN, next);
  console.log(`Wrote ${tours.length} tours into docs/apps-script-feedback-form.gs`);
  console.log("Synced the openable copy: docs/apps-script-feedback-form.js");
  console.log("Now re-run createForm() in the Apps Script editor.");
}
